library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity booth_fsm is
    Port ( 
        clk   : in  STD_LOGIC;
        rst   : in  STD_LOGIC;
        start : in  STD_LOGIC;
        A     : in  STD_LOGIC_VECTOR (3 downto 0); -- Multiplicand (M)
        B     : in  STD_LOGIC_VECTOR (3 downto 0); -- Multiplier (Q)
        Z     : out STD_LOGIC_VECTOR (7 downto 0); -- Product
        ready : out STD_LOGIC
    );
end booth_fsm;

architecture Behavioral of booth_fsm is
    -- ????? ???????? FSM
    type state_type is (IDLE, EVAL, SHIFT, DONE);
    signal state : state_type;

    -- ????????? ????? ???????? ???
    signal A_acc : signed(3 downto 0); -- ???????? (Accumulator)
    signal Q_reg : signed(3 downto 0); -- ?????? ????????? ??? B
    signal Q_1   : std_logic;          -- ??? Q(-1)
    signal M_reg : signed(3 downto 0); -- ?????? ????????? ??? A
    
    signal count : integer range 0 to 4; -- ??????? ???????

begin

    process(clk, rst)
    begin
        -- ???? ???????
        if rst = '1' then
            state <= IDLE;
            ready <= '0';
            Z     <= (others => '0');
            A_acc <= (others => '0');
            Q_reg <= (others => '0');
            Q_1   <= '0';
            M_reg <= (others => '0');
            count <= 0;
            
        -- ??? ???? ????? ????
        elsif rising_edge(clk) then
            case state is
            
                -- ???? ?????? ???? ????
                when IDLE =>
                    if start = '1' then
                        ready <= '0';  -- <--- ??? ???: ??? ???? ????? ???? ????? ???? ???
                        A_acc <= (others => '0');
                        Q_reg <= signed(B);
                        Q_1   <= '0';
                        M_reg <= signed(A);
                        count <= 4;
                        state <= EVAL;
                    end if;
                    
                -- ???? ??????? ?? ??? ???
                when EVAL =>
                    -- ????? Q_reg(0) ? Q_1
                    if Q_reg(0) = '1' and Q_1 = '0' then
                        A_acc <= A_acc - M_reg;
                    elsif Q_reg(0) = '0' and Q_1 = '1' then
                        A_acc <= A_acc + M_reg;
                    end if;
                    -- ?? ???? 00 ? 11 ??? ??????? ??? A_acc ????? ???????
                    state <= SHIFT;
                    
                -- ???? ???? ???????? ?? ????
                when SHIFT =>
                    -- Arithmetic Right Shift (ARS)
                    -- ??? ????? A_acc(3) ?? ??? ??? ??? ??????
                    A_acc <= A_acc(3) & A_acc(3 downto 1);
                    Q_reg <= A_acc(0) & Q_reg(3 downto 1);
                    Q_1   <= Q_reg(0);
                    
                    if count = 1 then
                        state <= DONE; -- ??? ? ??? ????? ??? ??? ?? ?????
                    else
                        count <= count - 1;
                        state <= EVAL; -- ?? ??? ??? ???? ????? ? ?????? ??????? ??
                    end if;
                    
                -- ???? ????? ??????
                when DONE =>
                    ready <= '1'; -- ?? ??? ?????? ????? ??????
                    Z     <= std_logic_vector(A_acc & Q_reg); -- ???? ???? ????? ?????
                    state <= IDLE; -- ?????? ?? ???? ?????? ???? ??? ????
                    
                -- ???? ??????? ???? ?????
                when others =>
                    state <= IDLE;
                    
            end case;
        end if;
    end process;

end Behavioral;